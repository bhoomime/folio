/* --------------------------------------------------------------- render */
let __ddId = 0;
function ddEntry(e, i, ctx) {
  const t = e[0];
  if (t === 'g') return `<g class="${e[1]}">${e[2].map((x) => ddEntry(x, i, ctx)).join('')}</g>`;
  ctx.n++;
  const d = `data-n="${ctx.n}"`;
  if (t === 'c') {
    const [, cx, cy, r, ty = 's'] = e;
    const fill = ty === 'af' || ty === 'f';
    return `<circle cx="${cx}" cy="${cy}" r="${r}" class="${ty}" ${fill ? '' : 'pathLength="1"'} ${d}/>`;
  }
  const fill = t === 'af' || t === 'f';
  return `<path d="${e[1]}" class="${t}" ${fill ? '' : 'pathLength="1"'} ${d}/>`;
}
/** Returns an SVG string. opts: { cls, pre (start undrawn), stagger, label } */
function doodle(name, opts = {}) {
  const D = DOODLES[name];
  if (!D) return '';
  const ctx = { n: 0, stagger: opts.stagger ?? .06 };
  const [w, h] = D.vb;
  const label = opts.label ? `role="img" aria-label="${opts.label}"` : 'aria-hidden="true" focusable="false"';
  return `<svg class="dd dd-${name} ${opts.cls || ''} ${opts.pre ? 'pre' : ''}" viewBox="0 0 ${w} ${h}" data-vbw="${w}" data-stagger="${ctx.stagger}" ${label}>${D.p.map((e, i) => ddEntry(e, i, ctx)).join('')}</svg>`;
}

/* --------------------------------------------------------------- seeded randomness */
function rng(seed) {
  let a = seed >>> 0 || 1;
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* --------------------------------------------------------------- sketchy frames
   Each edge is its own stroke that overshoots the corner a little, the way
   Bhoomie draws her frames (often doubled, never quite closed). */
function sketchEdge(x0, y0, x1, y1, R, wob) {
  const len = Math.hypot(x1 - x0, y1 - y0) || 1;
  const ux = (x1 - x0) / len, uy = (y1 - y0) / len;
  const o0 = (R() * 2 - .6) * 3.2, o1 = (R() * 2 - .6) * 3.2;
  const ax = x0 - ux * o0 + (R() - .5) * 1.6, ay = y0 - uy * o0 + (R() - .5) * 1.6;
  const bx = x1 + ux * o1 + (R() - .5) * 1.6, by = y1 + uy * o1 + (R() - .5) * 1.6;
  const bow = (R() - .5) * wob;
  const mx = (ax + bx) / 2 - uy * bow, my = (ay + by) / 2 + ux * bow;
  return `M${ax.toFixed(1)} ${ay.toFixed(1)}Q${mx.toFixed(1)} ${my.toFixed(1)} ${bx.toFixed(1)} ${by.toFixed(1)}`;
}
function sketchRect(w, h, seed = 1, { inset = 0, wob = 5 } = {}) {
  const R = rng(seed);
  const x0 = inset, y0 = inset, x1 = w - inset, y1 = h - inset;
  return [sketchEdge(x0, y0, x1, y0, R, wob), sketchEdge(x1, y0, x1, y1, R, wob), sketchEdge(x1, y1, x0, y1, R, wob), sketchEdge(x0, y1, x0, y0, R, wob)].join('');
}
/** A pill outline that wobbles and doesn't quite close, for buttons. */
function sketchPill(w, h, seed = 3) {
  const R = rng(seed);
  const r = h / 2, pts = [];
  const n = 48;
  for (let i = 0; i <= n + 3; i++) {
    const t = i / n;
    const per = 2 * (w - h) + Math.PI * h;
    let s = t * per, x, y;
    if (s < w - h) { x = r + s; y = 0; }
    else if ((s -= w - h) < Math.PI * r) { const a = -Math.PI / 2 + s / r; x = w - r + Math.cos(a) * r; y = r + Math.sin(a) * r; }
    else if ((s -= Math.PI * r) < w - h) { x = w - r - s; y = h; }
    else { s -= w - h; const a = Math.PI / 2 + s / r; x = r + Math.cos(a) * r; y = r + Math.sin(a) * r; }
    const j = Math.sin(t * 9 + seed) * .9 + (R() - .5) * .5;
    pts.push([x + j * .6, y + j * .5]);
  }
  return 'M' + pts.map((p) => p[0].toFixed(1) + ' ' + p[1].toFixed(1)).join('L');
}
